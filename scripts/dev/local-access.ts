// Local stand-in for Cloudflare Access. The Worker verifies these tokens with the same code
// as production; only the key source differs, and apps/worker/src/api/config.ts accepts a
// local key only with ENVIRONMENT=local and an issuer under the reserved `.invalid` domain.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { exportJWK, generateKeyPair, importJWK, SignJWT } from "jose";
import type { JWK } from "jose";
import { z } from "zod";
import { repositoryRoot } from "../shared/repository.ts";

const algorithm = "RS256";

export interface AccessKey {
  issuer: string;
  audience: string;
  privateJwk: JWK;
  publicJwk: JWK;
}

export interface AccessUser {
  subject: string;
  email: string;
}

export async function createAccessKey(issuer: string, audience: string): Promise<AccessKey> {
  const { privateKey, publicKey } = await generateKeyPair(algorithm, { extractable: true });
  const kid = crypto.randomUUID();
  return {
    issuer,
    audience,
    privateJwk: { ...(await exportJWK(privateKey)), kid, alg: algorithm },
    publicJwk: { ...(await exportJWK(publicKey)), kid, alg: algorithm, use: "sig" },
  };
}

/** Signs an Access-shaped JWT. `overrides` exist so tests can produce invalid tokens. */
export async function signAccessToken(
  key: AccessKey,
  user: AccessUser,
  overrides: { issuer?: string; audience?: string; expiresAt?: number } = {},
): Promise<string> {
  const privateKey = await importJWK(key.privateJwk, algorithm);
  return new SignJWT({ email: user.email })
    .setProtectedHeader({ alg: algorithm, kid: key.privateJwk.kid ?? "" })
    .setIssuer(overrides.issuer ?? key.issuer)
    .setAudience(overrides.audience ?? key.audience)
    .setSubject(user.subject)
    .setIssuedAt()
    .setExpirationTime(overrides.expiresAt ?? "30d")
    .sign(privateKey);
}

/** The Worker settings for a local run that trusts `key` and accepts `appOrigins`. */
export function localWorkerVars(
  key: AccessKey,
  appOrigins: readonly string[],
): Record<string, string> {
  return {
    ENVIRONMENT: "local",
    APP_ORIGINS: appOrigins.join(" "),
    ACCESS_TEAM_DOMAIN: key.issuer,
    ACCESS_AUD: key.audience,
    ACCESS_JWKS: JSON.stringify({ keys: [key.publicJwk] }),
  };
}

const generatedHeader = "# Generated by pnpm dev; edits are overwritten.";
// Accept files generated before the scripts directory was reorganized.
const legacyGeneratedHeader = "# Generated by scripts/local-access.ts; edits are overwritten.";

/** Formats an env file that wrangler reads (`.dev.vars` or `--env-file`). */
export function formatEnvFile(vars: Record<string, string>): string {
  const lines = Object.entries(vars).map(([name, value]) => {
    if (value.includes("'") || value.includes("\n")) {
      throw new Error(`Cannot quote ${name} for an env file`);
    }
    return `${name}='${value}'`;
  });
  return `${generatedHeader}\n${lines.join("\n")}\n`;
}

/** curl and the Vite banner use 127.0.0.1; the T3 preview opens localhost. */
export function devAppOrigins(web: number) {
  return [`http://127.0.0.1:${web}`, `http://localhost:${web}`];
}

export const devAccess = {
  issuer: "https://access.local.invalid",
  audience: "instant-madori-local",
  keyFile: new URL(".local/access-key.json", repositoryRoot),
  devVarsFile: new URL("apps/worker/.dev.vars", repositoryRoot),
  /** The signed-in developer; set MADORI_DEV_EMAIL to act as another user. */
  user(): AccessUser {
    const email = process.env["MADORI_DEV_EMAIL"] ?? "dev@example.com";
    return { subject: `local:${email}`, email };
  },
} as const;

const jwkSchema = z.looseObject({ kty: z.string(), kid: z.string() });
const accessKeySchema = z.object({
  issuer: z.string(),
  audience: z.string(),
  privateJwk: jwkSchema,
  publicJwk: jwkSchema,
});

/** The key file does not exist yet; every other read failure is reported as it is. */
export class MissingAccessKey extends Error {
  constructor() {
    super("The local Access key is missing. Start the app with `pnpm dev`.");
    this.name = "MissingAccessKey";
  }
}

function isMissingFile(error: unknown): boolean {
  return error instanceof Error && "code" in error && error.code === "ENOENT";
}

/** Reads a stored key; by default the persistent development key that `pnpm dev` creates. */
export async function readAccessKey(file: URL = devAccess.keyFile): Promise<AccessKey> {
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch (error) {
    throw isMissingFile(error) ? new MissingAccessKey() : error;
  }
  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    json = undefined;
  }
  const parsed = accessKeySchema.safeParse(json);
  if (!parsed.success) {
    throw new Error(`${fileURLToPath(file)} is malformed. Delete it and rerun.`);
  }
  return parsed.data;
}

/**
 * Creates the development key once and regenerates apps/worker/.dev.vars from it, refusing
 * to overwrite a .dev.vars that this script did not write.
 */
export async function ensureDevAccess(
  web: number,
  files: Pick<typeof devAccess, "keyFile" | "devVarsFile"> = devAccess,
): Promise<void> {
  let key: AccessKey;
  try {
    key = await readAccessKey(files.keyFile);
  } catch (error) {
    // Only a key that does not exist is created; an unreadable one is never replaced.
    if (!(error instanceof MissingAccessKey)) throw error;
    key = await createAccessKey(devAccess.issuer, devAccess.audience);
    await mkdir(dirname(fileURLToPath(files.keyFile)), { recursive: true });
    await writeFile(files.keyFile, JSON.stringify(key), { mode: 0o600, flag: "wx" });
  }
  const existing = await readFile(files.devVarsFile, "utf8").catch((error: unknown) => {
    if (isMissingFile(error)) return null;
    throw error;
  });
  if (
    existing !== null &&
    ![generatedHeader, legacyGeneratedHeader].includes(existing.split("\n")[0] ?? "")
  ) {
    throw new Error("apps/worker/.dev.vars was not generated by pnpm dev. Move it away first.");
  }
  await writeFile(files.devVarsFile, formatEnvFile(localWorkerVars(key, devAppOrigins(web))), {
    mode: 0o600,
  });
}
