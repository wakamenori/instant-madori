import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { pathToFileURL } from "node:url";
import {
  createAccessKey,
  ensureDevAccess,
  formatEnvFile,
  localWorkerVars,
  devAccess,
  devAppOrigins,
  MissingAccessKey,
  readAccessKey,
} from "./local-access.ts";

await test("Local Access key file", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "madori-access-key-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = (name: string) => pathToFileURL(join(directory, name));

  await t.test("a stored key reads back unchanged", async () => {
    const key = await createAccessKey("https://access.test.invalid", "aud");
    await writeFile(file("valid.json"), JSON.stringify(key));
    assert.deepEqual(await readAccessKey(file("valid.json")), key);
  });

  await t.test("a missing file asks the developer to run pnpm dev", async () => {
    await assert.rejects(readAccessKey(file("missing.json")), /Start the app with `pnpm dev`/);
  });

  await t.test("an unreadable key is reported as it is, never as missing", async () => {
    // A directory at the key's path cannot be read; treating it as missing would let
    // `pnpm dev` generate a new key and replace the developer's.
    await mkdir(join(directory, "unreadable.json"));
    await assert.rejects(readAccessKey(file("unreadable.json")), (error) => {
      assert.ok(!(error instanceof MissingAccessKey));
      return error instanceof Error && "code" in error && error.code === "EISDIR";
    });
  });

  for (const [label, content] of [
    ["truncated JSON", '{"issuer": "https://access'],
    ["JSON of the wrong shape", JSON.stringify({ issuer: "x" })],
  ] as const) {
    await t.test(`${label} gives the recovery message, not a raw parse error`, async () => {
      await writeFile(file("broken.json"), content);
      await assert.rejects(
        readAccessKey(file("broken.json")),
        /is malformed\. Delete it and rerun\./,
      );
    });
  }
});

await test("generated development vars ownership", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "madori-dev-vars-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const files = {
    keyFile: pathToFileURL(join(directory, "key.json")),
    devVarsFile: pathToFileURL(join(directory, ".dev.vars")),
  };
  const key = await createAccessKey(devAccess.issuer, devAccess.audience);
  await writeFile(files.keyFile, JSON.stringify(key));
  const storedKey = await readAccessKey(files.keyFile);
  const web = 24012;
  const marker = "# Generated by pnpm dev; edits are overwritten.";
  const expected = `${marker}\n${Object.entries(localWorkerVars(storedKey, devAppOrigins(web)))
    .map(([name, value]) => `${name}='${value}'`)
    .join("\n")}\n`;

  await t.test("new files use the path-free marker", async () => {
    assert.equal(formatEnvFile(localWorkerVars(storedKey, devAppOrigins(web))), expected);
    await ensureDevAccess(web, files);
    const contents = await readFile(files.devVarsFile, "utf8");
    assert.equal(contents, expected);
    assert.deepEqual(
      contents.split("\n").filter((line) => line.startsWith("APP_ORIGINS=")),
      ["APP_ORIGINS='http://127.0.0.1:24012 http://localhost:24012'"],
    );
  });
  for (const header of [marker, "# Generated by scripts/local-access.ts; edits are overwritten."]) {
    await t.test(`recognises and regenerates ${header}`, async () => {
      await writeFile(files.devVarsFile, `${header}\nSTALE='value'\n`);
      await ensureDevAccess(web, files);
      assert.equal(await readFile(files.devVarsFile, "utf8"), expected);
      assert.deepEqual(await readAccessKey(files.keyFile), key);
    });
  }
  await t.test("foreign files are refused and preserved", async () => {
    for (const content of ["USER_SETTING='keep'\n", `${marker} forged\n`, ""]) {
      await writeFile(files.devVarsFile, content);
      await assert.rejects(ensureDevAccess(web, files), /was not generated/);
      assert.equal(await readFile(files.devVarsFile, "utf8"), content);
    }
  });
});
