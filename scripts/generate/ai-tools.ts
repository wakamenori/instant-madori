import { createHash } from "node:crypto";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { z } from "zod";
import { strictToolSchemas } from "./strict-tool-schema.ts";

export function renderAiTools(input: unknown): string {
  const tools = z
    .array(
      z.object({
        name: z.string().regex(/^[a-z]+(?:_[a-z]+)*$/),
        input: z.record(z.string(), z.unknown()),
      }),
    )
    .parse(input);
  const list = strictToolSchemas(tools);
  const schemas = tools.map(({ name, input }) => {
    const type =
      name
        .split("_")
        .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
        .join("") + "Input";
    const variable = type.charAt(0).toLowerCase() + type.slice(1) + "Schema";
    const code = jsonSchemaToZod(input, { name: variable, module: "esm", noImport: true });
    if (/\bz\.any\s*\(/.test(code)) throw new Error(`${name}: unsupported schema emits z.any()`);
    return `${code}\nexport type ${type} = z.output<typeof ${variable}>;\n`;
  });
  const version = createHash("sha256").update(JSON.stringify(list)).digest("hex");
  return (
    '// Generated by pnpm generate:geometry. Do not edit.\nimport { z } from "zod";\n' +
    schemas.join("\n") +
    "\nexport const aiTools = Object.freeze([\n" +
    list.map((tool) => "  Object.freeze(" + JSON.stringify(tool) + " as const),").join("\n") +
    "\n] as const);\n" +
    `export const aiToolSchemaVersion = "sha256:${version}";\n`
  );
}
